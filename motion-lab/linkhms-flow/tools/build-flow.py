# Builds assets/flow.js from the Figma exports of the long flow (KK, page pp, frame "6", 193:15452).
#   assets/flow-long.svg  — the frame exported as SVG: one group per node, text outlined
#   tools/connectors.txt  — connector centerlines (flattened clones; five rebuilt by hand from the
#                           reference because flatten broke their routing): id|start|end|label|ox,oy|d
# Run: python3 tools/build-flow.py (from motion-lab/linkhms-flow)
import json, re

svg = open('assets/flow-long.svg').read()
body = svg[svg.find('<g id="Frame 1171276034">') + len('<g id="Frame 1171276034">'):]

groups, depth = [], 0
for m in re.finditer(r'<g id="([^"]*)"[^>]*>|</g>', body):
    if m.group(0).startswith('<g'):
        if depth == 0:
            name, start = m.group(1), m.start()
        depth += 1
    else:
        depth -= 1
        if depth == 0:
            groups.append((name, body[start:m.end()]))
        if depth < 0:
            break

# Figma nodes (id, x, y, w, h) from the frame's children
FIGMA = """15454 0 393 180 60|15456 758 393 180 60|15458 758 673 180 60|15460 1018 393 180 60|15462 1278 533 180 60|15464 1538 673 180 60|15466 1538 813 180 60|15469 1538 533 180 60|15471 1798 673 180 60|15473 1538 953 180 60|15476 1018 533 180 60|15478 1018 673 180 60|15480 1278 673 180 60|15482 498 253 180 60|15484 1798 813 180 60|15486 1538 3 180 310|15488 1278 253 180 60|15490 1538 393 180 60|15492 758 953 180 60|15494 1018 953 180 60|15496 1278 953 180 60|15499 498 533 180 60|15501 282 355 136 136|15504 1820 915 136 136|15507 1040 775 136 136|15510 780 775 136 136|15513 780 215 136 136|15516 1040 215 136 136|15519 1300 355 136 136|15522 1300 775 136 136|15525 1300 1055 136 136|15528 1040 1055 136 136|15531 780 1055 136 136|15534 1820 495 136 136|15537 1300 3 136 136|15541 520 355 136 136|15572 780 3 136 136"""
fig = [tuple(int(v) for v in s.split()) for s in FIGMA.split('|')]

def strip_ids(markup):
    return re.sub(r' id="[^"]*"', '', markup)

nodes = {}
labels = {}
for name, g in groups:
    if name in ('Yes', 'No', 'Yes_2', 'No_2'):
        t = re.search(r'<g id="Text Background[^"]*">\s*(<path[^>]*>)', g).group(1)
        labels[name] = strip_ids(t)
        continue
    if name.startswith('Connector'):
        continue
    r = re.search(r'<rect x="([\d.]+)" y="([\d.]+)" width="([\d.]+)" height="([\d.]+)"', g)
    c = re.search(r'<circle[^>]*cx="([\d.]+)" cy="([\d.]+)" r="([\d.]+)"', g)
    if 'rotate(45' in g:
        x, y = float(r.group(1)), float(r.group(2))
        cx, cy, kind = x, y + 70.71, 'diamond'
    elif c:
        cx, cy, kind = float(c.group(1)), float(c.group(2)), 'circle'
    else:
        x, y, w, h = (float(r.group(i)) for i in range(1, 5))
        cx, cy = x + w / 2, y + h / 2
        kind = 'pill' if 'rx="29.5"' in g else 'box'
    best = min(fig, key=lambda f: (f[1] + f[3] / 2 - cx) ** 2 + (f[2] + f[4] / 2 - cy) ** 2)
    fid, fx, fy, fw, fh = best
    assert abs(fx + fw / 2 - cx) < 2 and abs(fy + fh / 2 - cy) < 2, (name, cx, cy, best)
    inner = strip_ids(g[g.find('>') + 1:g.rfind('</g>')]).strip()
    nodes[str(fid)] = dict(kind=kind, x=fx, y=fy, w=fw, h=fh, svg=re.sub(r'\s*\n\s*', '', inner))

assert len(nodes) == len(fig), (len(nodes), len(fig))

LABEL_OF = {'15570': 'Yes', '15571': 'No', '15574': 'No_2', '15576': 'Yes_2'}

def shift(d, ox, oy):
    toks = re.findall(r'[MLCZ]|-?\d+\.?\d*', d)
    out, i, coord = [], 0, 0
    for tk in toks:
        if tk in 'MLCZ':
            out.append(tk); coord = 0
        else:
            v = float(tk) + (ox if coord % 2 == 0 else oy)
            coord += 1
            out.append(('%.1f' % v).rstrip('0').rstrip('.'))
    return ' '.join(out)

edges = []
for line in open('tools/connectors.txt').read().strip().split('\n'):
    cid, s, e, lab, o, d = line.split('|')
    ox, oy = (float(v) for v in o.split(','))
    # keep the line subpath (the last one that isn't closed); glyphs come from the SVG
    subs = [sp.strip() for sp in re.split(r'(?=M )', d) if sp.strip()]
    subs = [sp for sp in subs if not sp.endswith('Z')]
    edge = dict(id=cid, s=s, e=e, d=shift(subs[-1], ox, oy))
    if cid in LABEL_OF:
        edge['label'] = labels[LABEL_OF[cid]]
    edges.append(edge)

with open('assets/flow.js', 'w') as f:
    f.write('// Generated by tools/build-flow.py from the Figma long flow (193:15452). Flow-frame coordinates.\n')
    f.write('const NODES = ' + json.dumps(nodes, ensure_ascii=False, indent=0) + ';\n')
    f.write('const EDGES = ' + json.dumps(edges, ensure_ascii=False, indent=0) + ';\n')
print(len(nodes), 'nodes', len(edges), 'edges', sorted(k for k in labels))
